import type { LabOrderItem } from '@ceenaix/types';
import type { PatientLabOrderRecord } from '@/data/web/hooks/use-patient-lab-results';

export function labItemValue(item: LabOrderItem): string {
  if (item.numeric_value != null) return item.result_unit ? `${item.numeric_value} ${item.result_unit}` : String(item.numeric_value);
  if (item.result_value?.trim()) return item.result_unit ? `${item.result_value} ${item.result_unit}` : item.result_value;
  return '';
}

export function labItemReference(item: LabOrderItem): string | null {
  return item.reference_text ?? item.reference_range ?? null;
}

/** Position (0–100) of the value on a simple reference bar, matching the web zone heuristics. */
export function labItemMarker(item: LabOrderItem): number | null {
  if (item.numeric_value == null) return null;
  const zoneMaxes = (item.reference_zones ?? [])
    .map((zone) => (typeof zone.max === 'number' ? zone.max : null))
    .filter((value): value is number => value != null);
  if (zoneMaxes.length > 0) {
    const axis = Math.max(...zoneMaxes) * 1.15;
    if (axis > 0) return Math.min(98, Math.max(2, (item.numeric_value / axis) * 100));
  }
  if (item.reference_max != null && item.reference_max > 0) {
    const upper = Math.max(item.reference_max * 1.6, item.numeric_value);
    return Math.min(100, Math.max(2, (item.numeric_value / upper) * 100));
  }
  if (item.reference_min != null && item.reference_min > 0) {
    const upper = Math.max(item.reference_min * 2, item.numeric_value);
    return Math.min(100, Math.max(2, (item.numeric_value / upper) * 100));
  }
  return null;
}

/** Plain-text report, same content as the web "share" text, handed to the native share sheet. */
export function buildLabReportText(order: PatientLabOrderRecord, dateLabel: string): string {
  const lines = [
    'LAB RESULTS REPORT',
    '==================',
    `Lab:    ${order.labName ?? 'Unknown Lab'}`,
    `Date:   ${dateLabel}`,
    `Doctor: ${order.doctorName ?? 'Unknown'}`,
  ];
  if (order.lab_order_code) lines.push(`Order:  ${order.lab_order_code}`);
  lines.push('', 'TEST RESULTS', '------------');
  for (const item of order.parentItems) {
    const value = labItemValue(item) || 'Pending';
    const flag = item.is_abnormal ? ' [ABNORMAL]' : '';
    lines.push(`${item.test_name}: ${value} — ${item.status_label ?? item.status_category}${flag}`);
    if (item.reference_text) lines.push(`  Ref: ${item.reference_text}`);
  }
  if (order.overall_comment) lines.push('', 'DOCTOR COMMENT', '--------------', order.overall_comment);
  lines.push('', 'Generated by CeenAiX Health Platform');
  return lines.join('\n');
}
