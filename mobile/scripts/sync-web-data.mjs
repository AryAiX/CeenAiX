#!/usr/bin/env node
// Generates `src/data/web/**` from the web portal's patient data hooks so the
// native app runs the exact same Supabase queries (tables, columns,
// `is_deleted` / status filters, RPCs) as the web — no hand-copied drift.
//
// Only import specifiers are rewritten:
//   ../lib/supabase           -> @/lib/supabase (AsyncStorage-backed native client)
//   ../lib/<supabase-backed>  -> ../lib/<file> (also generated here)
//   ../lib/<pure helper>      -> @ceenaix/shared/<file>
//   ../types                  -> @ceenaix/types
//   ./use-query               -> @/hooks/use-query (same contract as web)
//
// Usage: `npm run sync:web` to regenerate, `npm run sync:web -- --check` in CI
// to fail when the generated copy is stale.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const webSrc = path.resolve(mobileRoot, '..', 'src');
const outRoot = path.join(mobileRoot, 'src', 'data', 'web');

const HOOKS = [
  'use-appointments',
  'use-bookable-doctors',
  'use-doctor-booking-availability',
  'use-imaging-studies',
  'use-medication-logs',
  'use-messaging-hub',
  'use-notifications',
  'use-patient-ai-chat',
  'use-patient-appointment-detail',
  'use-patient-dashboard',
  'use-patient-document-vault',
  'use-patient-insurance',
  'use-patient-lab-results',
  'use-patient-notifications',
  'use-patient-prescriptions',
  'use-patient-records',
  'use-pre-visit',
  'use-specializations',
];

// Web lib files that import `./supabase` and therefore cannot be shared as-is.
const SUPABASE_LIBS = ['ai', 'canonical-record-updates', 'lab-test-catalog', 'medication-catalog', 'telemedicine'];
const NATIVE_LIBS = { supabase: '@/lib/supabase' };

const header = (source) =>
  `// AUTO-GENERATED by mobile/scripts/sync-web-data.mjs from ${source}.\n// Do not edit — change the web file and run \`npm run sync:web\`.\n`;

const rewrite = (code, kind) =>
  code.replace(/(from\s+|import\s*\(\s*)'([^']+)'/g, (match, prefix, spec) => {
    let next = spec;
    if (kind === 'hook') {
      const lib = spec.match(/^\.\.\/lib\/(.+)$/)?.[1];
      if (lib) next = NATIVE_LIBS[lib] ?? (SUPABASE_LIBS.includes(lib) ? `../lib/${lib}` : `@ceenaix/shared/${lib}`);
      else if (spec === '../types') next = '@ceenaix/types';
      else if (spec === './use-query') next = '@/hooks/use-query';
      else if (spec.startsWith('./') && !HOOKS.includes(spec.slice(2))) {
        throw new Error(`Unsupported hook import "${spec}" — add it to HOOKS or replace it natively.`);
      }
    } else {
      const lib = spec.match(/^\.\/(.+)$/)?.[1];
      if (lib) next = NATIVE_LIBS[lib] ?? (SUPABASE_LIBS.includes(lib) ? `./${lib}` : `@ceenaix/shared/${lib}`);
      else if (spec === '../types') next = '@ceenaix/types';
    }
    return `${prefix}'${next}'`;
  });

const outputs = new Map();
for (const name of HOOKS) {
  const source = `src/hooks/${name}.ts`;
  outputs.set(path.join(outRoot, 'hooks', `${name}.ts`), header(source) + rewrite(readFileSync(path.join(webSrc, 'hooks', `${name}.ts`), 'utf8'), 'hook'));
}
for (const name of SUPABASE_LIBS) {
  const source = `src/lib/${name}.ts`;
  outputs.set(path.join(outRoot, 'lib', `${name}.ts`), header(source) + rewrite(readFileSync(path.join(webSrc, 'lib', `${name}.ts`), 'utf8'), 'lib'));
}

const check = process.argv.includes('--check');
const stale = [];
for (const [file, contents] of outputs) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== contents) stale.push(path.relative(mobileRoot, file));
}
for (const dir of ['hooks', 'lib']) {
  const full = path.join(outRoot, dir);
  if (!existsSync(full)) continue;
  for (const entry of readdirSync(full)) {
    const file = path.join(full, entry);
    if (!outputs.has(file)) stale.push(`${path.relative(mobileRoot, file)} (orphan)`);
  }
}

if (check) {
  if (stale.length) {
    console.error(`Generated web data layer is stale:\n  ${stale.join('\n  ')}\nRun \`npm run sync:web\` in mobile/.`);
    process.exit(1);
  }
  console.log('Web data layer is up to date.');
} else {
  rmSync(outRoot, { recursive: true, force: true });
  for (const [file, contents] of outputs) {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, contents);
  }
  console.log(`Synced ${outputs.size} files into ${path.relative(mobileRoot, outRoot)}.`);
}
